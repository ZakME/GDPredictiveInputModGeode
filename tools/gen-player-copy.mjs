// Generates src/generated/PlayerStateCopy.inc from the Geode bindings: one
// assignment per plain-value PlayerObject member, so the simulator clone starts
// with exactly the real player's physics state.
// Usage: node tools/gen-player-copy.mjs <path to GeometryDash.bro>
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const broPath = process.argv[2];
if (!broPath) {
    console.error("usage: node tools/gen-player-copy.mjs <GeometryDash.bro>");
    process.exit(2);
}

const lines = readFileSync(broPath, "utf8").split(/\r?\n/);
const start = lines.findIndex((l) => /^class PlayerObject\b/.test(l));
if (start < 0) throw new Error("class PlayerObject not found");

// Value types that are safe to copy with operator=.
const copyable = new Set([
    "bool", "int", "float", "double", "unsigned char", "unsigned int", "short",
    "cocos2d::CCPoint", "cocos2d::ccColor3B", "ShipStreak", "GhostType",
    "geode::SeedValueRSV",
]);

// Non-owning pointers into the level that physics reads (slopes, ground,
// portal, dash orb). Owned nodes (sprites, particles, streaks) are skipped.
const levelPointers = new Set([
    "m_maybeLastGroundObject", "m_currentSlope2", "m_preLastGroundObject",
    "m_collidedObject", "m_lastGroundObject", "m_collidingWithLeft",
    "m_collidingWithRight", "m_currentPotentialSlope", "m_currentSlope",
    "m_objectSnappedTo", "m_lastActivatedPortal", "m_dashRing",
]);

// Value-type containers holding per-player orb/pad/button bookkeeping.
const containers = new Set([
    "m_ringRelatedSet", "m_touchedRings", "m_jumpPadRelated", "m_holdingButtons",
    "m_potentialSlopeMap", "m_rotateObjectsRelated",
]);

const out = [];
let skipped = [];
for (let i = start + 1; i < lines.length && !/^}/.test(lines[i]); i++) {
    const m = lines[i].match(/^\s+([A-Za-z_][\w:<>, ]*?\*?)\s+(m_\w+)(\[(\d+)\])?;/);
    if (!m) continue;
    const [, type, name, , arrayLen] = m;
    const t = type.trim();
    if (arrayLen && copyable.has(t)) {
        out.push(`std::copy(std::begin(src->${name}), std::end(src->${name}), std::begin(dst->${name}));`);
    } else if (copyable.has(t) || levelPointers.has(name) || containers.has(name)) {
        out.push(`dst->${name} = src->${name};`);
    } else {
        skipped.push(`${t} ${name}`);
    }
}

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "generated", "PlayerStateCopy.inc");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target,
    "// Generated by tools/gen-player-copy.mjs from the Geode 2.2091 bindings. Do not edit.\n" +
    "// Expects `PlayerObject* dst` and `PlayerObject* src` in scope.\n" +
    out.join("\n") + "\n");
console.log(`wrote ${out.length} assignments to ${target}; skipped ${skipped.length}:`);
console.log(skipped.join("\n"));
